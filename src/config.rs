use std::{collections::HashSet, net::SocketAddr, time::Duration};

use age::{secrecy::ExposeSecret, x25519::Identity};
use anyhow::{Context, Result, bail, ensure};

const MIN_API_KEY_LEN: usize = 32;
const MIN_PASSWORD_LEN: usize = 12;

/// Runtime configuration. Deliberately not `Debug`: it holds secrets.
pub struct Config {
    pub listen_addr: SocketAddr,
    pub ollama_url: String,
    pub database_url: String,
    /// `(name, key)` pairs.
    pub api_keys: Vec<(String, String)>,
    pub admin_user: String,
    pub admin_password: String,
    pub identity: Identity,
    pub cookie_secure: bool,
    pub ollama_timeout: Duration,
    pub max_body_bytes: usize,
}

impl Config {
    pub fn from_env() -> Result<Self> {
        let config = Self {
            listen_addr: optional("ADUANA_LISTEN_ADDR", "0.0.0.0:8080")
                .parse()
                .context("ADUANA_LISTEN_ADDR is not a valid socket address")?,
            ollama_url: optional("ADUANA_OLLAMA_URL", "http://host.docker.internal:11434"),
            database_url: optional("ADUANA_DATABASE_URL", "sqlite:///data/aduana.db"),
            api_keys: parse_api_keys(&required("ADUANA_API_KEYS")?)?,
            admin_user: optional("ADUANA_ADMIN_USER", "admin"),
            admin_password: required("ADUANA_ADMIN_PASSWORD")?,
            identity: parse_identity(&required("ADUANA_AGE_IDENTITY")?)?,
            cookie_secure: optional("ADUANA_COOKIE_SECURE", "true")
                .parse()
                .context("ADUANA_COOKIE_SECURE must be true or false")?,
            ollama_timeout: Duration::from_secs(
                optional("ADUANA_OLLAMA_TIMEOUT_SECS", "600")
                    .parse()
                    .context("ADUANA_OLLAMA_TIMEOUT_SECS must be a number of seconds")?,
            ),
            max_body_bytes: optional("ADUANA_MAX_BODY_BYTES", "33554432")
                .parse()
                .context("ADUANA_MAX_BODY_BYTES must be a number of bytes")?,
        };
        ensure!(
            config.admin_password.len() >= MIN_PASSWORD_LEN,
            "ADUANA_ADMIN_PASSWORD must be at least {MIN_PASSWORD_LEN} characters"
        );
        Ok(config)
    }
}

fn required(name: &str) -> Result<String> {
    std::env::var(name).with_context(|| format!("{name} is required (see README)"))
}

fn optional(name: &str, default: &str) -> String {
    std::env::var(name).unwrap_or_else(|_| default.to_owned())
}

fn parse_identity(value: &str) -> Result<Identity> {
    // The parse error can echo key material, so it is replaced, not wrapped.
    value
        .trim()
        .parse()
        .map_err(|_| anyhow::anyhow!("ADUANA_AGE_IDENTITY is not a valid age secret key"))
}

/// Parses `name:key,name2:key2`.
pub fn parse_api_keys(value: &str) -> Result<Vec<(String, String)>> {
    let mut seen = HashSet::new();
    let mut keys = Vec::new();
    for entry in value.split(',').map(str::trim).filter(|e| !e.is_empty()) {
        let Some((name, key)) = entry.split_once(':') else {
            bail!("ADUANA_API_KEYS entries must look like name:key");
        };
        ensure!(
            !name.is_empty(),
            "ADUANA_API_KEYS has an entry without a name"
        );
        ensure!(
            key.len() >= MIN_API_KEY_LEN,
            "API key '{name}' must be at least {MIN_API_KEY_LEN} characters"
        );
        ensure!(seen.insert(name), "API key name '{name}' is duplicated");
        keys.push((name.to_owned(), key.to_owned()));
    }
    ensure!(
        !keys.is_empty(),
        "ADUANA_API_KEYS must define at least one key"
    );
    Ok(keys)
}

/// Renders a ready-to-use `.env` file with freshly generated secrets.
pub fn generate_env() -> Result<String> {
    let identity = Identity::generate();
    Ok(format!(
        "# Generated by `aduana gen-env`. Keep this file private and back it up:\n\
         # losing ADUANA_AGE_IDENTITY makes every stored request unreadable.\n\
         ADUANA_API_KEYS=default:{api_key}\n\
         ADUANA_ADMIN_USER=admin\n\
         ADUANA_ADMIN_PASSWORD={password}\n\
         ADUANA_AGE_IDENTITY={identity}\n\
         # Set to true as soon as the panel is served over HTTPS.\n\
         ADUANA_COOKIE_SECURE=false\n",
        api_key = crate::auth::random_hex(32)?,
        password = crate::auth::random_hex(16)?,
        identity = identity.to_string().expose_secret(),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    const KEY: &str = "0123456789abcdef0123456789abcdef";

    #[test]
    fn parses_multiple_keys() {
        let keys = parse_api_keys(&format!("a:{KEY}, b:{KEY}x")).unwrap();
        assert_eq!(keys.len(), 2);
        assert_eq!(keys[1].0, "b");
    }

    #[test]
    fn rejects_weak_or_malformed_keys() {
        assert!(parse_api_keys("").is_err());
        assert!(parse_api_keys("nocolon").is_err());
        assert!(parse_api_keys("a:short").is_err());
        assert!(parse_api_keys(&format!(":{KEY}")).is_err());
        assert!(parse_api_keys(&format!("a:{KEY},a:{KEY}")).is_err());
    }

    #[test]
    fn generated_env_contains_a_usable_identity() {
        let env = generate_env().unwrap();
        let line = env
            .lines()
            .find_map(|l| l.strip_prefix("ADUANA_AGE_IDENTITY="))
            .unwrap();
        assert!(parse_identity(line).is_ok());
    }
}
